#!/usr/bin/env python3
"""ExpenseBuddy MCP server.

The LLM interprets natural language and calls structured tools. Python owns
validation, persistence, and timestamps.

Tools:
  record_expense(amount, category, comment)
  fetch_expenses(days)
  delete_expense(expense_id)

Storage: expenses.csv beside this file.
Transport: Streamable HTTP on http://0.0.0.0:8000/mcp
"""

from __future__ import annotations

import csv
import hashlib
import re
import uuid
from datetime import date, datetime, timedelta
from decimal import Decimal, InvalidOperation
from pathlib import Path
from urllib.parse import parse_qs

from mcp.server.mcpserver import Context, MCPServer
import uvicorn

mcp = MCPServer("ExpenseBuddy")

BASE_DIR = Path(__file__).resolve().parent
CSV_FILE = BASE_DIR / "expenses.csv"
CSV_HEADERS = ["id", "date", "time", "amount", "category", "comment"]

CATEGORIES = {
    "Food",
    "Petrol",
    "Recharge",
    "Entertainment",
    "Sports",
    "Travel",
    "Health",
    "Personal Care",
    "Shopping",
    "Household",
    "Other",
}

USER_CODE_PATTERN = re.compile(r"^[A-Za-z0-9_-]{8}$")


class RequireUserCodeMiddleware:
    """Reject MCP HTTP requests before protocol handling unless user is a 16-char code."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] == "http" and scope.get("path") == "/mcp":
            query = parse_qs(scope.get("query_string", b"").decode("ascii", errors="ignore"))
            values = query.get("user", [])
            if len(values) != 1 or not USER_CODE_PATTERN.fullmatch(values[0]):
                body = (
                    b"Connection rejected: the MCP connection URL must include "
                    b"?user=<8-character-random-code>."
                )
                await send(
                    {
                        "type": "http.response.start",
                        "status": 400,
                        "headers": [(b"content-type", b"text/plain; charset=utf-8")],
                    }
                )
                await send({"type": "http.response.body", "body": body})
                return

        await self.app(scope, receive, send)


def csv_file_for_user(ctx: Context) -> Path:
    """Choose an expense file from the connection URL's ?user= value."""
    request = ctx.request_context.request
    user_code = request.query_params.get("user", "").strip() if request is not None else ""
    if not user_code:
        return CSV_FILE

    # Hash the supplied code so URL values cannot escape the storage directory.
    user_hash = hashlib.sha256(user_code.encode("utf-8")).hexdigest()[:24]
    return BASE_DIR / f"expenses_{user_hash}.csv"


def ensure_csv(csv_file: Path) -> None:
    """Create the expense CSV with headers if it does not exist."""
    if not csv_file.exists():
        with csv_file.open("w", encoding="utf-8", newline="") as file:
            csv.writer(file).writerow(CSV_HEADERS)


def validate_amount(amount: float | int | str) -> str:
    """Validate and normalize an expense amount to two decimal places."""
    try:
        value = Decimal(str(amount))
    except (InvalidOperation, ValueError):
        raise ValueError("Amount must be a valid number.")

    if value <= 0:
        raise ValueError("Amount must be greater than zero.")

    if value.as_tuple().exponent < -2:
        raise ValueError("Amount can have at most two decimal places.")

    return f"{value:.2f}"


@mcp.tool()
def record_expense(amount: float, category: str, comment: str, ctx: Context) -> str:
    """Record one expense.

    The LLM should provide structured values. For example, for
    '2000 Zudio', it should call this as amount=2000, category='Shopping',
    comment='Zudio'. Date and time are generated by Python, not the LLM.
    """
    try:
        normalized_category = category.strip().title()

        if normalized_category not in CATEGORIES:
            return (
                f"Error: invalid category '{category}'. Allowed categories: "
                + ", ".join(sorted(CATEGORIES))
            )

        normalized_comment = comment.strip()

        if not normalized_comment:
            return "Error: comment cannot be empty."

        normalized_amount = validate_amount(amount)

        now = datetime.now().astimezone()
        expense_id = uuid.uuid4().hex[:12]

        csv_file = csv_file_for_user(ctx)
        ensure_csv(csv_file)

        with csv_file.open(
            "a",
            encoding="utf-8",
            newline="",
        ) as file:
            csv.writer(file).writerow(
                [
                    expense_id,
                    now.date().isoformat(),
                    now.strftime("%H:%M:%S %z"),
                    normalized_amount,
                    normalized_category,
                    normalized_comment,
                ]
            )

        return (
            f"Expense recorded successfully. "
            f"ID: {expense_id}; "
            f"amount: {normalized_amount}; "
            f"category: {normalized_category}; "
            f"comment: {normalized_comment}; "
            f"date: {now.date().isoformat()}; "
            f"time: {now.strftime('%H:%M:%S %z')}"
        )

    except (OSError, ValueError) as exc:
        return f"Error recording expense: {exc}"


@mcp.tool()
def delete_expense(expense_id: str, ctx: Context) -> str:
    """Delete an expense using its ID.

    The expense ID must come from fetch_expenses().
    """
    expense_id = expense_id.strip()

    if not expense_id:
        return "Error: expense_id cannot be empty."

    try:
        csv_file = csv_file_for_user(ctx)
        ensure_csv(csv_file)

        rows: list[dict[str, str]] = []
        deleted_row: dict[str, str] | None = None

        with csv_file.open(
            "r",
            encoding="utf-8",
            newline="",
        ) as file:
            reader = csv.DictReader(file)

            for row in reader:
                if row.get("id") == expense_id:
                    deleted_row = row
                else:
                    rows.append(row)

        if deleted_row is None:
            return f"Error: No expense found with ID '{expense_id}'."

        # Rewrite the CSV without the deleted expense.
        temp_file = csv_file.with_suffix(".tmp")

        with temp_file.open(
            "w",
            encoding="utf-8",
            newline="",
        ) as file:
            writer = csv.DictWriter(
                file,
                fieldnames=CSV_HEADERS,
            )

            writer.writeheader()
            writer.writerows(rows)

        # Atomically replace the original CSV.
        temp_file.replace(csv_file)

        return (
            "Expense deleted successfully.\n"
            f"ID: {deleted_row['id']}\n"
            f"Amount: {deleted_row['amount']}\n"
            f"Category: {deleted_row['category']}\n"
            f"Comment: {deleted_row['comment']}\n"
            f"Date: {deleted_row['date']}\n"
            f"Time: {deleted_row['time']}"
        )

    except (PermissionError, OSError, ValueError) as exc:
        return f"Error deleting expense: {exc}"


@mcp.tool()
def fetch_expenses(days: int, ctx: Context) -> str:
    """Fetch expenses from the last N calendar days, including today.

    Python calculates the date range. The LLM only supplies the number of days.
    """
    if not isinstance(days, int) or isinstance(days, bool) or days < 1:
        return "Error: days must be a positive integer."

    if days > 3650:
        return "Error: days cannot exceed 3650."

    try:
        csv_file = csv_file_for_user(ctx)
        ensure_csv(csv_file)

        today = date.today()
        start_date = today - timedelta(days=days - 1)

        expenses: list[dict[str, str]] = []

        with csv_file.open(
            "r",
            encoding="utf-8",
            newline="",
        ) as file:
            for row in csv.DictReader(file):
                try:
                    expense_date = date.fromisoformat(row["date"])
                except (KeyError, ValueError):
                    continue

                if start_date <= expense_date <= today:
                    expenses.append(row)

        expenses.sort(
            key=lambda row: (row["date"], row["time"]),
            reverse=True,
        )

        if not expenses:
            return (
                f"No expenses found for the last {days} calendar day(s) "
                f"({start_date.isoformat()} to {today.isoformat()})."
            )

        total = sum(
            Decimal(row["amount"])
            for row in expenses
        )

        lines = [
            f"Expenses for {start_date.isoformat()} to {today.isoformat()}",
            f"Total: {total:.2f}",
            f"Count: {len(expenses)}",
            "",
        ]

        for index, row in enumerate(expenses, start=1):
            lines.append(
                f"{index}. "
                f"{row['date']} {row['time']} | "
                f"{row['amount']} | "
                f"{row['category']} | "
                f"{row['comment']} | "
                f"ID: {row['id']}"
            )

        return "\n".join(lines)

    except (OSError, ValueError) as exc:
        return f"Error fetching expenses: {exc}"


if __name__ == "__main__":
    host = "0.0.0.0"
    port = 8000
    app = mcp.streamable_http_app(host=host)
    app = RequireUserCodeMiddleware(app)

    print(
        "Starting ExpenseBuddy MCP server...\n"
        f"Storage: {CSV_FILE}\n"
        f"Endpoint: http://{host}:{port}/mcp?user=<8-character-random-code>"
    )

    uvicorn.run(app, host=host, port=port, log_level="info")
